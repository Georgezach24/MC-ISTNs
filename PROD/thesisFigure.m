function fig = thesisFigure(widthCm, heightCm)
%THESISFIGURE Κοινό στυλ γραφημάτων: λευκό φόντο, Arial 9 pt, μέγεθος σε cm
% (πλάτος σελίδας ~16-17 cm), ώστε τα κείμενα να έχουν ίδιο μέγεθος σε όλα.
%   fig = thesisFigure(17, 9)
fig = figure('Visible', 'off', 'Color', 'w', 'Units', 'centimeters', ...
    'Position', [2 2 widthCm heightCm], 'PaperUnits', 'centimeters', ...
    'PaperSize', [widthCm heightCm]);
try
    theme(fig, 'light');
catch
end
set(fig, 'DefaultAxesFontName', 'Arial', 'DefaultTextFontName', 'Arial', ...
    'DefaultAxesFontSize', 9, 'DefaultTextFontSize', 9, ...
    'DefaultAxesTitleFontSizeMultiplier', 1.05, 'DefaultAxesTitleFontWeight', 'bold', ...
    'DefaultAxesLabelFontSizeMultiplier', 1, ...
    'DefaultAxesXColor', [0.25 0.25 0.25], 'DefaultAxesYColor', [0.25 0.25 0.25], ...
    'DefaultAxesGridColor', [0.80 0.80 0.80], 'DefaultAxesGridAlpha', 0.6, ...
    'DefaultAxesBox', 'off', 'DefaultAxesTickDir', 'out', ...
    'DefaultAxesLineWidth', 0.6, 'DefaultLineLineWidth', 1.2, ...
    'DefaultLegendBox', 'off', 'DefaultLegendFontSize', 8.5);
end
